const edges = [
  ["app.mjs",          "my-lib", "import"],
  ["app.mjs",          "lodash", "import"],
  ["old-wrapper.cjs",  "my-lib", "require"],
  ["old-wrapper.cjs",  "chalk",  "require"],
  ["utils.mjs",        "my-lib", "import"],
];

function findDualHazards(edges) {
  const conditions = {};

  for (const [, specifier, condition] of edges) {
    if (!conditions[specifier]) conditions[specifier] = new Set();
    conditions[specifier].add(condition);
  }

  const hazards = [];
  for (const [pkg, conds] of Object.entries(conditions)) {
    if (conds.has("import") && conds.has("require")) {
      hazards.push(pkg);
    }
  }
  return hazards;
}

const hazards = findDualHazards(edges);
console.log("Dual-package hazard candidates:", hazards);
// ["my-lib"] — loaded as both ESM and CJS in the same graph
